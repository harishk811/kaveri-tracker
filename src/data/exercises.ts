export const getExerciseById = (id: string): Exercise | undefined =>
  EXERCISES.find((e) => e.id === id)

export const getExercisesByCategory = (category: Exercise['category']): Exercise[] =>
  EXERCISES.filter((e) => e.category === category)

export const getStrengthAExercises = (): Exercise[] => {
  const primer = EXERCISES.filter((e) => e.category === 'primerA')
  const main = EXERCISES.filter((e) => e.category === 'mainA')
  const shin = EXERCISES.filter((e) => e.category === 'shinA')
  return [...primer, ...main, ...shin]
}

export const getStrengthBExercises = (): Exercise[] => {
  const primer = EXERCISES.filter((e) => e.category === 'primerB')
  const main = EXERCISES.filter((e) => e.category === 'mainB')
  const arms = EXERCISES.filter((e) => e.category === 'armsB')
  const core = EXERCISES.filter((e) => e.category === 'coreB')
  return [...primer, ...main, ...arms, ...core]
}

export const getStrengthCExercises = (): Exercise[] => {
  const plyo = EXERCISES.filter((e) => e.category === 'plyoC')
  const durability = EXERCISES.filter((e) => e.category === 'durabilityC')
  return [...plyo, ...durability]
}

export const getDailyShinExercises = (): Exercise[] =>
  EXERCISES.filter((e) => e.category === 'dailyShin')

export const getMobilityExercises = (): Exercise[] =>
  EXERCISES.filter((e) => e.category === 'mobility')

// Strength slot → exercise list resolver
export const getExercisesForSlot = (slot: 'A' | 'B' | 'C'): Exercise[] => {
  if (slot === 'A') return getStrengthAExercises()
  if (slot === 'B') return getStrengthBExercises()
  return getStrengthCExercises()
}

